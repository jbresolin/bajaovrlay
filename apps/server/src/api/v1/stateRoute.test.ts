/**
 * GET /api/v1/state and the OpenAPI document (apps/server)
 *
 * What this module is for:
 *   `GET /api/v1/state` returns every slice at once. The renderer calls it when it
 *   reconnects, and anyone can call it to see what the server holds. Routes under
 *   /api/v1 are declared with their Zod schemas, from which the OpenAPI document at
 *   `/api/v1/openapi.json` is generated.
 *
 * What these tests prove:
 *   - The state answer passes the shared SlicesSchema and shows the seeded layers.
 *   - A command applied to the store shows up in the next answer.
 *   - The OpenAPI document describes GET /state, and is still generated with the
 *     `previewClearedLayerIds` slice (BAJAOVRLAY-36) in the state it describes.
 *   - At boot the state carries that slice, empty.
 *
 * What these tests deliberately do not cover:
 *   - The WebSocket, which pushes the same slices as they change (core/ws tests).
 *   - Every field of the OpenAPI document; it is generated by @hono/zod-openapi.
 */
import { SlicesSchema } from '@bajaovrlay/shared';
import { describe, expect, it } from 'vitest';

import { openTemporaryDatabase } from '../../core/db/temporaryDatabase.testSupport.js';
import { createServerApp } from '../../core/http/createServerApp.js';
import { createLogger } from '../../core/logger/createLogger.js';
import { createGraphicsFolderWithBuiltRaceClock } from '../../core/store/builtGraphicsFolder.testSupport.js';
import { createStateStore } from '../../core/store/createStateStore.js';

/** Builds the server app on a freshly seeded store, without opening a port. */
function createServerAppWithSeededStore() {
  const logger = createLogger({ level: 'silent' });
  const stateStore = createStateStore({
    database: openTemporaryDatabase().database,
    logger,
    graphicPackagesFolder: createGraphicsFolderWithBuiltRaceClock(),
  });
  const app = createServerApp({ logger, version: '0.3.1', stateStore });
  return { app, stateStore };
}

describe('GET /api/v1/state', () => {
  it('answers every slice, passing the shared schema, with the seeded layers', async () => {
    // Arrange: a server app on a store seeded at its first boot.
    const { app } = createServerAppWithSeededStore();

    // Act: ask for the state, as the renderer does when it reconnects.
    const response = await app.request('/api/v1/state');
    const body: unknown = await response.json();

    // Assert: 200, a body the shared schema accepts, and the five layers in order.
    const parsedBody = SlicesSchema.safeParse(body);
    expect(response.status, 'the state must answer 200 OK').toBe(200);
    expect(parsedBody.success, 'the body must pass the shared SlicesSchema').toBe(true);
    expect(
      parsedBody.data?.layers.map((layer) => layer.id),
      'the seeded layers must be in the answer, bottom to top',
    ).toEqual(['bug', 'ticker', 'clock', 'lower-third', 'fullscreen']);
  });

  it('shows the instance a command just put on air', async () => {
    // Arrange: a server app whose store has just taken the race clock.
    const { app, stateStore } = createServerAppWithSeededStore();
    stateStore.applyCommand(
      {
        type: 'takeGraphic',
        graphicId: 'race-clock',
        layerId: 'clock',
        // All six fields the race clock's manifest schema requires: the enduro under
        // green flag, 1:05:00 in and running.
        data: {
          sessionName: 'Enduro de Resistência',
          state: 'green',
          clockMode: 'elapsed',
          referenceTimeMs: 3_900_000,
          referenceWallClockMs: 1_791_550_800_000,
          running: true,
        },
      },
      'operador:conexao-7',
    );

    // Act: ask for the state.
    const response = await app.request('/api/v1/state');
    const body = SlicesSchema.parse(await response.json());

    // Assert: the race clock instance is in the answer.
    expect(
      body.instances.map((instance) => [instance.graphicId, instance.layerId]),
      'the race clock must be on the clock layer',
    ).toEqual([['race-clock', 'clock']]);
  });
});

describe('GET /api/v1/openapi.json', () => {
  it('describes GET /state with its 200 answer', async () => {
    // Arrange: a server app on a seeded store.
    const { app } = createServerAppWithSeededStore();

    // Act: ask for the OpenAPI document.
    const response = await app.request('/api/v1/openapi.json');
    const document = (await response.json()) as {
      openapi: string;
      paths: Record<string, Record<string, { responses: Record<string, unknown> }>>;
    };

    // Assert: an OpenAPI 3.1 document listing GET /state with a 200 answer.
    expect(response.status, 'the OpenAPI document must answer 200 OK').toBe(200);
    expect(document.openapi, 'the document must be OpenAPI 3.1').toBe('3.1.0');
    expect(
      document.paths['/state']?.get?.responses['200'],
      'GET /state must be described with its 200 answer',
    ).toBeDefined();
  });

  it('is still generated with the "will be cleared" markers in the state it describes', async () => {
    // Arrange: a server app on a seeded store.
    const { app } = createServerAppWithSeededStore();

    // Act: ask for the OpenAPI document and read it as text.
    const response = await app.request('/api/v1/openapi.json');
    const documentText = await response.text();

    // Assert: generated, and the newest slice (BAJAOVRLAY-36) is part of what it describes.
    expect(response.status, 'the OpenAPI document must answer 200 OK').toBe(200);
    expect(documentText, 'the state described must list the markers slice').toContain(
      'previewClearedLayerIds',
    );
  });
});

describe('GET /api/v1/state at boot', () => {
  it('answers with no "will be cleared" marker', async () => {
    // Arrange: a server app on a store seeded at its first boot.
    const { app } = createServerAppWithSeededStore();

    // Act: ask for the state.
    const response = await app.request('/api/v1/state');
    const body = SlicesSchema.parse(await response.json());

    // Assert: the markers slice is there and empty: Prévia starts with nothing marked.
    expect(body.previewClearedLayerIds, 'a boot must start with no marker').toEqual([]);
  });
});
