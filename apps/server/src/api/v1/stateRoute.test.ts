/**
 * GET /api/v1/state and the OpenAPI document (apps/server)
 *
 * What this module is for:
 *   `GET /api/v1/state` returns every slice at once. The renderer calls it when it
 *   reconnects, and anyone can call it to see what the server holds. Routes under
 *   /api/v1 are declared with their Zod schemas, from which the OpenAPI document at
 *   `/api/v1/openapi.json` is generated.
 *
 *   A renderer page whose hello is late calls it with its own role (`?role=renderer` for
 *   the page OBS loads, `?role=monitor` for the control page's frames), and then gets
 *   the same slices the WebSocket hub gives that role: the four a screen draws (layers,
 *   graphics, instances, previewClearedLayerIds) and every other slice empty, because
 *   graphics receive resolved data only and an older page must not meet a slice its
 *   schemas refuse (João's ruling at gate 2 of PR #17).
 *
 * What these tests prove:
 *   - The state answer passes the shared SlicesSchema and shows the seeded layers.
 *   - With no role it carries every slice as the store holds it; with `?role=renderer`
 *     or `?role=monitor` the four drawn slices are as the store holds them and each of
 *     the nine other slices, every one holding something on the server (a macro run and
 *     a recording included), is an empty list; an unknown role is answered 400 with a
 *     pt-BR message.
 *   - A command applied to the store shows up in the next answer.
 *   - The OpenAPI document describes GET /state with its `role` query parameter, and
 *     is still generated with the `previewClearedLayerIds` slice (BAJAOVRLAY-36) in the
 *     state it describes.
 *   - At boot the state carries that slice, empty.
 *
 * What these tests deliberately do not cover:
 *   - The WebSocket, which pushes the same slices as they change (core/ws tests).
 *   - Every field of the OpenAPI document; it is generated by @hono/zod-openapi.
 */
import { SlicesSchema } from '@bajaovrlay/shared';
import { describe, expect, it } from 'vitest';

import { openTemporaryDatabase } from '../../core/db/temporaryDatabase.testSupport.js';
import { createServerApp } from '../../core/http/createServerApp.js';
import { createLogger } from '../../core/logger/createLogger.js';
import { operatorLoginOff } from '../../core/operatorLogin/operatorLoginOff.testSupport.js';
import { createGraphicsFolderWithBuiltRaceClock } from '../../core/store/builtGraphicsFolder.testSupport.js';
import { createStateStore } from '../../core/store/createStateStore.js';
import { createRaceClockItemOnTheStore } from '../../core/store/raceClockItemOnTheStore.testSupport.js';
import {
  fillEverySliceAScreenIsNotSent,
  listHiddenSlicesTheServerHoldsNothingIn,
} from '../../core/ws/hiddenSlicesFilledOnTheStore.testSupport.js';
import { buildTheCopyAScreenShouldGet } from '../../core/ws/slicesSentToScreens.testSupport.js';

/** Builds the server app on a freshly seeded store, without opening a port. */
function createServerAppWithSeededStore() {
  const logger = createLogger({ level: 'silent' });
  const stateStore = createStateStore({
    database: openTemporaryDatabase().database,
    logger,
    graphicPackagesFolder: createGraphicsFolderWithBuiltRaceClock(),
  });
  const app = createServerApp({
    logger,
    operatorLogin: operatorLoginOff,
    version: '0.3.1',
    stateStore,
  });
  return { app, stateStore };
}

describe('GET /api/v1/state', () => {
  it('answers every slice, passing the shared schema, with the seeded layers', async () => {
    // Arrange: a server app on a store seeded at its first boot.
    const { app } = createServerAppWithSeededStore();

    // Act: ask for the state, as the renderer does when it reconnects.
    const response = await app.request('/api/v1/state');
    const body: unknown = await response.json();

    // Assert: 200, a body the shared schema accepts, and the ten layers in order.
    const parsedBody = SlicesSchema.safeParse(body);
    expect(response.status, 'the state must answer 200 OK').toBe(200);
    expect(parsedBody.success, 'the body must pass the shared SlicesSchema').toBe(true);
    expect(
      parsedBody.data?.layers.map((layer) => layer.id),
      'the seeded layers must be in the answer, bottom to top',
    ).toEqual([
      'bug',
      'sponsor-roll-plain',
      'channel-logo',
      'bracket-match',
      'ticker',
      'clock',
      'tower',
      'lower-third',
      'notice',
      'fullscreen',
    ]);
  });

  it('shows the instance a command just put on air', async () => {
    // Arrange: a server app whose store has just taken the race clock item.
    const { app, stateStore } = createServerAppWithSeededStore();
    const raceClockItemId = createRaceClockItemOnTheStore(stateStore);
    stateStore.applyCommand({ type: 'takeItem', itemId: raceClockItemId }, 'operador:conexao-7');

    // Act: ask for the state.
    const response = await app.request('/api/v1/state');
    const body = SlicesSchema.parse(await response.json());

    // Assert: the race clock instance is in the answer, naming its item.
    expect(
      body.instances.map((instance) => [instance.graphicId, instance.layerId, instance.itemId]),
      'the race clock of the item must be on the clock layer',
    ).toEqual([['race-clock', 'clock', raceClockItemId]]);
  });
});

const roleScenarios = [
  // Anyone else (a curl while debugging, a future tool) still sees everything.
  {
    name: 'answers every slice when no role is given',
    address: '/api/v1/state',
    isAScreen: false,
  },
  // The page OBS loads, reading the state because its hello is late.
  {
    name: 'answers only the four drawn slices, the rest empty, to ?role=renderer',
    address: '/api/v1/state?role=renderer',
    isAScreen: true,
  },
  // The control page's "Programa" and "Prévia" frames, in the same situation.
  {
    name: 'answers only the four drawn slices, the rest empty, to ?role=monitor',
    address: '/api/v1/state?role=monitor',
    isAScreen: true,
  },
];

describe('GET /api/v1/state with a role', () => {
  it.each(roleScenarios)('$name', async ({ address, isAScreen }) => {
    // Arrange: a server app with something in every slice a screen is not sent: an item,
    // a macro and its run (this store has no runner, so the run stays), and the simulator
    // recorded and polled once by hand (this store has no poller).
    const { app, stateStore } = createServerAppWithSeededStore();
    fillEverySliceAScreenIsNotSent(stateStore);
    const slicesOnTheServer = stateStore.readAllSlices();

    // Act: ask for the state at the address of the row.
    const response = await app.request(address);
    const body = SlicesSchema.parse(await response.json());

    // Assert: 200, and the slices are all there or a screen's copy, as the role decides.
    const expectedBody = isAScreen
      ? buildTheCopyAScreenShouldGet(slicesOnTheServer)
      : slicesOnTheServer;
    expect(
      listHiddenSlicesTheServerHoldsNothingIn(slicesOnTheServer),
      'every slice a screen is not sent must hold something on the server, so its emptiness on a screen is proven',
    ).toEqual([]);
    expect(response.status, 'the state must answer 200 OK').toBe(200);
    expect(body, 'a screen gets only what it draws; anyone else gets all').toEqual(expectedBody);
  });

  it('answers 400 with a pt-BR message to a role it does not know', async () => {
    // Arrange: a server app on a seeded store.
    const { app } = createServerAppWithSeededStore();

    // Act: ask for the state with a role that is neither renderer nor monitor.
    const response = await app.request('/api/v1/state?role=narrador');
    const body: unknown = await response.json();

    // Assert: 400, with a stable code and the two roles named in pt-BR.
    expect(response.status, 'an unknown role must be refused, not answered').toBe(400);
    expect(body, 'the refusal must say which roles exist').toEqual({
      error: {
        code: 'INVALID_STATE_ROLE',
        message: 'O parâmetro "role" aceita apenas "renderer" ou "monitor".',
      },
    });
  });
});

describe('GET /api/v1/openapi.json', () => {
  it('describes GET /state with its 200 answer', async () => {
    // Arrange: a server app on a seeded store.
    const { app } = createServerAppWithSeededStore();

    // Act: ask for the OpenAPI document.
    const response = await app.request('/api/v1/openapi.json');
    const document = (await response.json()) as {
      openapi: string;
      paths: Record<
        string,
        Record<string, { responses: Record<string, unknown>; parameters?: { name: string }[] }>
      >;
    };

    // Assert: an OpenAPI 3.1 document listing GET /state with a 200 answer.
    expect(response.status, 'the OpenAPI document must answer 200 OK').toBe(200);
    expect(document.openapi, 'the document must be OpenAPI 3.1').toBe('3.1.0');
    expect(
      document.paths['/state']?.get?.responses['200'],
      'GET /state must be described with its 200 answer',
    ).toBeDefined();
    expect(
      document.paths['/state']?.get?.parameters?.map((parameter) => parameter.name),
      'GET /state must describe its role and output query parameters (output: BAJAOVRLAY-49)',
    ).toEqual(['role', 'output']);
  });

  it('is still generated with the "will be cleared" markers in the state it describes', async () => {
    // Arrange: a server app on a seeded store.
    const { app } = createServerAppWithSeededStore();

    // Act: ask for the OpenAPI document and read it as text.
    const response = await app.request('/api/v1/openapi.json');
    const documentText = await response.text();

    // Assert: generated, and the newest slice (BAJAOVRLAY-36) is part of what it describes.
    expect(response.status, 'the OpenAPI document must answer 200 OK').toBe(200);
    expect(documentText, 'the state described must list the markers slice').toContain(
      'previewClearedLayerIds',
    );
  });
});

describe('GET /api/v1/state at boot', () => {
  it('answers with no "will be cleared" marker', async () => {
    // Arrange: a server app on a store seeded at its first boot.
    const { app } = createServerAppWithSeededStore();

    // Act: ask for the state.
    const response = await app.request('/api/v1/state');
    const body = SlicesSchema.parse(await response.json());

    // Assert: the markers slice is there and empty: Prévia starts with nothing marked.
    expect(body.previewClearedLayerIds, 'a boot must start with no marker').toEqual([]);
  });
});
