import { mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

import Database from 'better-sqlite3';
import { type BetterSQLite3Database, drizzle } from 'drizzle-orm/better-sqlite3';
import { migrate } from 'drizzle-orm/better-sqlite3/migrator';

/** The server's database: Drizzle over one better-sqlite3 connection (`$client`). */
export type ServerDatabase = BetterSQLite3Database & { $client: Database.Database };

// This file sits three levels below apps/server both as source (src/core/db/) and when
// built (dist/core/db/), so the same relative path reaches apps/server/drizzle in both.
/** The migrations generated by drizzle-kit and committed in apps/server/drizzle/. */
export const committedMigrationsFolder = fileURLToPath(
  new URL('../../../drizzle/', import.meta.url),
);

/**
 * Opens (or creates) the SQLite file and applies every migration not applied yet.
 * Throws if any migration fails, after closing the file: the server must never run on
 * a half-migrated database, so the boot stops instead ("fail closed").
 */
export function openDatabase(options: {
  databasePath: string;
  migrationsFolder: string;
}): ServerDatabase {
  // The default path (apps/server/data/) does not exist in a fresh clone.
  mkdirSync(dirname(options.databasePath), { recursive: true });
  const connection = new Database(options.databasePath);
  const database = drizzle({ client: connection });

  try {
    migrate(database, { migrationsFolder: options.migrationsFolder });
  } catch (migrationError) {
    connection.close();
    throw new Error(`database migration failed (migrations folder: ${options.migrationsFolder})`, {
      cause: migrationError,
    });
  }
  return database;
}
